function moduleOrderForLesson(order: number) {
  return Math.min(Math.floor((order - 1) / 4) + 1, 5);
}

function lessonSkills(title: string, focus: string) {
  const cleaned = title.replace(/[:;,]/g, ' ');
  const words = cleaned.split(/\s+/).filter((word) => word.length > 3).slice(0, 3);
  return Array.from(new Set([focus, title, ...words]));
}

function makeRoadmap(grade: GradeLevel): LessonRoadmapItem[] {
  return lessonTitles[grade].map((title, index) => {
    const order = index + 1;
    const moduleOrder = moduleOrderForLesson(order);
    const focus = moduleFocus[grade][moduleOrder - 1] ?? moduleFocus[grade][0];

    return {
      grade,
      order,
      moduleOrder,
      title,
      objective: `Освоить тему «${title}» через понимание, практику и объяснение решения.`,
      skills: lessonSkills(title, focus),
    };
  });
}

